# -*- coding: utf-8 -*-
"""
Sales/Member/Product 3테이블 병합 + 외부 거시/계절 변수 결합 스크립트.
원본: data/raw/{Sales_Data,Member_Data,Product_Data}.csv (cp949)
산출: data/processed/merged_master.csv (utf-8-sig)

외부변수 출처는 같은 폴더의 외부변수_출처.md 참고.
"""
import pandas as pd
import numpy as np

RAW = r"C:\Users\aidan\OneDrive\바탕 화면\종합실습\data\raw"
OUT = r"C:\Users\aidan\OneDrive\바탕 화면\종합실습\data\processed"

# ---------------------------------------------------------------
# 1. 원본 로드
# ---------------------------------------------------------------
sales = pd.read_csv(f"{RAW}\\Sales_Data.csv", encoding="cp949")
member = pd.read_csv(f"{RAW}\\Member_Data.csv", encoding="cp949")
product = pd.read_csv(f"{RAW}\\Product_Data.csv", encoding="cp949")

n_sales_before = len(sales)

# ---------------------------------------------------------------
# 2. 회원상태 컬럼 충돌 처리 (Sales/Member 양쪽에 존재)
#    -> Member 쪽을 정본으로 채택하고, 두 값이 불일치하는 건수를 기록
# ---------------------------------------------------------------
sales = sales.rename(columns={"회원상태": "회원상태_sales당시"})

merged = sales.merge(
    member, on="회원번호", how="left", validate="many_to_one"
)
merged = merged.merge(
    product, on="제품번호", how="left", validate="many_to_one"
)

assert len(merged) == n_sales_before, "조인 후 행 수가 변했습니다 (fan-out 발생)"

mismatch = (merged["회원상태_sales당시"] != merged["회원상태"]).sum()
merged = merged.drop(columns=["회원상태_sales당시"])  # Member 회원상태를 정본으로 채택

# ---------------------------------------------------------------
# 3. 날짜/시간 파생
# ---------------------------------------------------------------
merged["주문일시"] = pd.to_datetime(merged["주문일시"], errors="coerce")
merged["배송시작일"] = pd.to_datetime(merged["배송시작일"], errors="coerce")
merged["배송완료일"] = pd.to_datetime(merged["배송완료일"], errors="coerce")

order_date = merged["주문일시"].dt.date.astype("datetime64[ns]")
month = merged["주문일시"].dt.month
merged["주문년월"] = merged["주문일시"].dt.to_period("M").astype(str)

# ---------------------------------------------------------------
# 4. 계절 (직접 계산)
# ---------------------------------------------------------------
def to_season(m):
    if m in (3, 4, 5):
        return "봄"
    if m in (6, 7, 8):
        return "여름"
    if m in (9, 10, 11):
        return "가을"
    return "겨울"

merged["계절"] = month.apply(to_season)

# ---------------------------------------------------------------
# 5. 일단위 특보/연휴 플래그
#    ※ 기상특보(폭염/한파/집중호우)는 기상자료개방포털의 지역별 일단위 원자료에
#      직접 접근하지 못해, 언론·기상청 보도자료에 나온 "발효 시기 범위"를
#      근사치로 적용함. 정밀 일자료가 아니므로 출처 문서에 한계를 명시함.
# ---------------------------------------------------------------
def date_range(start, end):
    return pd.date_range(start, end).date

폭염_기간 = set(date_range("2025-07-15", "2025-08-25"))  # 근사치 (본문 참조)
한파_기간 = set(date_range("2025-01-24", "2025-01-29"))  # 확인된 구간(남부지방)
집중호우_기간 = set(date_range("2025-06-12", "2025-07-31"))  # 근사치 (장마 시작~종료 추정)

연휴_날짜 = set(date_range("2025-01-01", "2025-01-01")) \
    | set(date_range("2025-01-29", "2025-01-31")) \
    | set(date_range("2025-03-01", "2025-03-01")) \
    | set(date_range("2025-05-05", "2025-05-06")) \
    | set(date_range("2025-05-08", "2025-05-08")) \
    | set(date_range("2025-06-06", "2025-06-06")) \
    | set(date_range("2025-08-15", "2025-08-15")) \
    | set(date_range("2025-09-29", "2025-10-01")) \
    | set(date_range("2025-10-03", "2025-10-03")) \
    | set(date_range("2025-10-09", "2025-10-09"))

od = order_date.dt.date
merged["폭염주의보_발효"] = od.isin(폭염_기간)
merged["한파주의보_발효"] = od.isin(한파_기간)
merged["집중호우_발효"] = od.isin(집중호우_기간)
merged["연휴여부"] = od.isin(연휴_날짜)

# ---------------------------------------------------------------
# 6. 기준금리 (일단위, 실제 금통위 결정일 반영 — 출처 문서 참조)
# ---------------------------------------------------------------
def base_rate(d):
    if d < pd.Timestamp("2025-02-25").date():
        return 3.00
    if d < pd.Timestamp("2025-05-29").date():
        return 2.75
    return 2.50

merged["기준금리(%)"] = od.apply(base_rate)

# ---------------------------------------------------------------
# 7. 월별 지표 조인 (year-month 기준)
#    결측은 검색으로 확인 못한 달 — NaN 유지 (임의보정 금지)
# ---------------------------------------------------------------
신선식품지수_전월비 = {
    # 통계청 월별 소비자물가동향 보도자료(신선식품지수 전월대비 %). 전 항목 확인 완료(2라운드).
    "2025-01": 0.7, "2025-02": -1.4, "2025-03": -1.3, "2025-04": -1.9,
    "2025-05": -5.0, "2025-06": -2.1, "2025-07": -0.5, "2025-08": 2.1,
    "2025-09": -2.5, "2025-10": -0.5, "2025-11": -0.8,
}

ccsi = {
    # 한국은행 소비자동향조사 보도자료. 직접 확인: 2,3,5,6,7,9,11월. 나머지는 인접월의
    # "전월대비 X포인트 상승/하락" 공식 문구를 그대로 역산(1,4,8,10월) — 지어낸 값 아님.
    "2025-01": 91.2,   # 역산: 2월 95.2 - 4.0p
    "2025-02": 95.2,   # 확인
    "2025-03": 93.4,   # 확인 (2월 95.2 - 1.8p 와 일치)
    "2025-04": 93.8,   # 역산: 5월 101.8 - 8.0p
    "2025-05": 101.8,  # 확인
    "2025-06": 108.7,  # 확인
    "2025-07": 110.8,  # 확인 (6월 108.7 + 2.1p 와 일치)
    "2025-08": 111.4,  # 역산: 9월 110.1 + 1.3p
    "2025-09": 110.1,  # 확인
    "2025-10": 109.8,  # 역산: 11월 112.4 - 2.6p
    "2025-11": 112.4,  # 확인
}

# "원자재(식자재) 가격지수"는 단일 공식 통계로 존재하지 않음(3라운드 재확인) — 원컬럼은 만들지 않고,
# 통계청 CPI "농축수산물" 소분류 전월대비(%)를 정식 대체 변수로 채택함(옵션1).
# 3라운드에서 6월 실측치(-0.6%) 추가 확보. 1·3월은 여러 경로(korea.kr/KDI/KOSIS)로 재시도했으나
# 보도자료 본문 요약에는 방향(상승)만 있고 정확한 %가 hwp/pdf 원문에만 있어 끝내 확인 못함.
# "추가 변수에 결측 있으면 안 됨" 요구사항에 따라, 아래 2개월은 선형보간/최근값연장으로 채우고
# 별도 플래그 컬럼(농축수산물지수_보간여부)에 True로 표시함 — 지어낸 값이 아니라 보간임을 명시.
농축수산물_전월비 = {
    "2025-01": 1.7,   # [보간] 실측치 없음. 2월 확정치(1.7)를 그대로 앞으로 연장(1월 이전 데이터가 없어 선형보간 불가)
    "2025-02": 1.7,   # 실측
    "2025-03": -0.05, # [보간] 2월(1.7)과 4월(-1.8) 사이 선형보간: 1.7 + (-1.8-1.7)/2
    "2025-04": -1.8,  # 실측
    "2025-05": -2.6,  # 실측
    "2025-06": -0.6,  # 실측 (3라운드 신규 확보)
    "2025-07": 1.5,   # 실측
    "2025-08": 4.8,   # 실측
    "2025-09": 0.0,   # 실측 ("변동없음" 명시적 보도)
    "2025-10": 0.1,   # 실측
    "2025-11": 3.1,   # 실측
}
농축수산물_보간여부 = {
    "2025-01": True, "2025-02": False, "2025-03": True, "2025-04": False,
    "2025-05": False, "2025-06": False, "2025-07": False, "2025-08": False,
    "2025-09": False, "2025-10": False, "2025-11": False,
}

# 두바이유 월평균(달러/배럴) — 3라운드에서 IndexMundi(Dubai Fateh 월별 시계열)로 실제 월별값 확보,
# 기존 KEEI 분기평균(76.94/66.91/70.09/63.84)은 동일 방향·유사 크기로 교차검증됨(±3달러 이내).
두바이유_월평균 = {
    "2025-01": 80.14, "2025-02": 74.97, "2025-03": 71.71, "2025-04": 66.89,
    "2025-05": 63.01, "2025-06": 68.50, "2025-07": 69.23, "2025-08": 67.87,
    "2025-09": 67.75, "2025-10": 64.30, "2025-11": 63.83,
}

merged["신선식품지수_전월대비(%)"] = merged["주문년월"].map(신선식품지수_전월비)
merged["소비자심리지수_CCSI"] = merged["주문년월"].map(ccsi)
merged["두바이유_평균유가(달러/배럴)"] = merged["주문년월"].map(두바이유_월평균)

# 농축수산물지수 — 원자재(식자재) 가격지수의 정식 대체 변수로 승격 (원컬럼 "원자재_식자재_가격지수"는 삭제)
merged["농축수산물지수_전월대비(%)"] = merged["주문년월"].map(농축수산물_전월비)
merged["농축수산물지수_보간여부"] = merged["주문년월"].map(농축수산물_보간여부)

# 출산율: 2025년 합계출산율(연간, 0.80) — 월별 세분 수치는 신뢰도 낮아 채택 보류, 연간값 균등 적용
merged["합계출산율(연간값 적용)"] = 0.80

# ---------------------------------------------------------------
# 8. 저장
# ---------------------------------------------------------------
merged.to_csv(f"{OUT}\\merged_master.csv", index=False, encoding="utf-8-sig")

print("=== 결과 요약 ===")
print("shape:", merged.shape)
print("회원상태 불일치(Sales vs Member):", mismatch, "건")
print("컬럼:", list(merged.columns))
